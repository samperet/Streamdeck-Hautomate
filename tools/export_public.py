#!/usr/bin/env python3
"""Copy this deck into a folder for the public, open-source repo, without this house's data.

    python3 tools/export_public.py [TARGET]        # default ~/streamdeck-home

Takes the files git tracks at HEAD, leaves out what's personal or not ours to share (PRIVATE),
puts example people in people/, and writes the public .gitignore. The target's own .git is kept,
so exporting again and committing there publishes the changes. Files in the target that aren't
exported are removed, except .git and what the public .gitignore covers (settings.yaml, caches).
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = Path(sys.argv[1] if len(sys.argv) > 1 else "~/streamdeck-home").expanduser()

# never exported: this house's notes and people, a list that's one person's, a font whose licence
# doesn't allow sharing it, and generated files
PRIVATE = {"CLAUDE.md", "configuration.yaml", "albums/medicina.json", "fonts/ChicagoFLF.ttf"}
PRIVATE_DIRS = ("people/",)

EXAMPLE_PEOPLE = {  # people/<file>.json for the example settings: a few albums each
    "alex": [
        {"kind": "album", "id": "1weenld61qoidwYuZ1GESA", "title": "Kind Of Blue", "artist": "Miles Davis"},
        {"kind": "album", "id": "0ETFjACtuP2ADo6LFhL6HN", "title": "Abbey Road", "artist": "The Beatles"},
    ],
    "riley": [],
}

GITIGNORE = """\
# Your house (copy settings.example.yaml) and secrets
settings.yaml
.env
manager/.env
manager/spotify_user.json
emulator/.live-auth.js

# Generated by gen_config.py and emulator/build.py
configuration.yaml
emulator/streamdeck-emulator-local.html
emulator/.build-version.js
emulator/.build.lock
emulator/.cache
.*.tmp

# Fonts you add yourself (see fonts/README.md)
fonts/*.ttf
fonts/*.otf

__pycache__/
*.pyc
"""


def tracked() -> list[str]:
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return [f for f in out.splitlines() if f not in PRIVATE and not f.startswith(PRIVATE_DIRS)]


def main():
    TARGET.mkdir(parents=True, exist_ok=True)
    files = tracked()
    written = set()
    for rel in files:
        src, dst = ROOT / rel, TARGET / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        written.add(rel)
    for slug, items in EXAMPLE_PEOPLE.items():
        rel = f"people/{slug}.json"
        (TARGET / rel).parent.mkdir(exist_ok=True)
        (TARGET / rel).write_text(json.dumps(items, indent=1) + "\n")
        written.add(rel)
    (TARGET / ".gitignore").write_text(GITIGNORE)
    written.add(".gitignore")
    # drop files exported before that aren't any more (keep .git and ignored local files)
    keep = {"settings.yaml", ".env", "configuration.yaml"}
    for f in sorted(TARGET.rglob("*"), reverse=True):
        rel = f.relative_to(TARGET).as_posix()
        if rel.startswith((".git/", "emulator/.cache", "fonts/")) or rel in (".git",) or "__pycache__" in rel:
            continue
        if f.is_file() and rel not in written and rel not in keep and not rel.startswith("emulator/streamdeck-emulator"):
            f.unlink()
        elif f.is_dir() and not any(f.iterdir()):
            f.rmdir()
    print(f"exported {len(written)} files to {TARGET}")


if __name__ == "__main__":
    main()
